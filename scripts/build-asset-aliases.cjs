// Run after changing game art: node scripts/build-asset-aliases.cjs
// Only byte-identical images share a URL; original files and pose keys stay intact.
const { createHash } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

function buildAliases() {
  const seen = new Map();
  const aliases = {};
  function visit(dir) {
    for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
      const file = dir + '/' + entry.name;
      if (entry.isDirectory()) visit(file);
      else if (/\.(png|jpg|jpeg|webp)$/i.test(file)) {
        const hash = createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex');
        if (seen.has(hash)) aliases[file] = seen.get(hash);
        else seen.set(hash, file);
      }
    }
  }
  visit('assets');
  return aliases;
}

function output(aliases) {
  return '// Generated by scripts/build-asset-aliases.cjs; do not edit by hand.\n' +
    'window.TPAssetAliases = Object.freeze(' + JSON.stringify(aliases, null, 2) + ');\n';
}

if (require.main === module) {
  const generated = output(buildAliases());
  const target = path.join(root, 'src/asset-aliases.js');
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) {
      console.error('Asset aliases are stale. Run node scripts/build-asset-aliases.cjs');
      process.exitCode = 1;
    }
  } else fs.writeFileSync(target, generated);
}

module.exports = { buildAliases, output };
